"""
Phase 3 — Memory write/promote/forget/inject policy decisions.

``MemoryPolicy`` is the gatekeeper between raw events / LLM candidates and
the persistent memory store.  Every write, promotion, or forgetting action
flows through a policy check so the system cannot silently corrupt long-term
memory with low-confidence or conflicting content.

Policy decisions are deterministic (rule-based), not LLM-driven, so they
execute fast and are auditable.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from enum import Enum

from .models import MemoryRecord, MemoryType, Scope


class WriteDecision(str, Enum):
    """Outcome of a write-policy check."""

    AUTO_WRITE = "auto_write"          # write directly, no confirmation
    CANDIDATE = "candidate"            # write as candidate, needs review
    SHORT_TERM_ONLY = "short_term"     # keep in L0/L1 only, don't persist
    REJECT = "reject"                  # don't write at all
    CONFIRM = "confirm"                # ask player before writing


class PromoteDecision(str, Enum):
    """Whether a short-term memory should be promoted to long-term."""

    PROMOTE = "promote"
    KEEP_SHORT = "keep_short"
    DISCARD = "discard"


class InjectDecision(str, Enum):
    """How a memory should be injected into the prompt."""

    FULL = "full"           # inject full body
    SUMMARY = "summary"     # inject description only
    INDEX_ONLY = "index"    # name appears in index, detail loaded on demand
    SKIP = "skip"           # don't inject


@dataclass
class PolicyResult:
    decision: WriteDecision
    reason: str = ""
    suggested_scope: Scope | None = None
    suggested_type: MemoryType | None = None
    suggested_confidence: float | None = None


@dataclass
class InjectPlan:
    """Specifies which records to inject and at what detail level."""

    full: list[MemoryRecord] = field(default_factory=list)
    summary: list[MemoryRecord] = field(default_factory=list)
    index: list[str] = field(default_factory=list)  # just names
    total_tokens_est: int = 0


class MemoryPolicy:
    """Rule-based gatekeeper for memory lifecycle decisions."""

    # ── Write policy ───────────────────────────────────────────────────

    def evaluate_write(
        self,
        record: MemoryRecord,
        *,
        is_player_requested: bool = False,
        is_llm_reflection: bool = False,
        conflicts_exist: bool = False,
        tombstone_hit: bool = False,
    ) -> PolicyResult:
        """Decide whether *record* should be written and at what confidence level.

        Args:
            record: The candidate record to evaluate.
            is_player_requested: True if the player explicitly typed ``remember X``.
            is_llm_reflection: True if generated by the reflection worker.
            conflicts_exist: True if an existing record with the same name/type exists.
            tombstone_hit: True if this name has been explicitly forgotten.
        """
        # Hard reject: tombstone
        if tombstone_hit:
            return PolicyResult(
                WriteDecision.REJECT,
                reason="entity is in tombstone deny-list",
            )

        # Player-requested writes are trusted
        if is_player_requested:
            conf = max(record.confidence, 0.85)
            return PolicyResult(
                WriteDecision.AUTO_WRITE,
                reason="player explicitly requested",
                suggested_confidence=conf,
            )

        # LLM reflection — lower trust, needs more gating
        if is_llm_reflection:
            if record.source == "llm_reflected":
                if record.confidence >= 0.8:
                    return PolicyResult(
                        WriteDecision.AUTO_WRITE,
                        reason="high-confidence reflection",
                        suggested_confidence=min(record.confidence, 0.8),
                    )
                elif record.confidence >= 0.5:
                    return PolicyResult(
                        WriteDecision.CANDIDATE,
                        reason="medium-confidence reflection — review needed",
                        suggested_confidence=record.confidence,
                    )
                else:
                    return PolicyResult(
                        WriteDecision.SHORT_TERM_ONLY,
                        reason="low-confidence reflection — keep in L1 only",
                    )
            # Reflection with non-standard source — more careful
            return PolicyResult(
                WriteDecision.CANDIDATE,
                reason="reflection with non-standard source",
                suggested_confidence=min(record.confidence, 0.6),
            )

        # Bot-observed facts: auto-write if high confidence, candidate otherwise
        if record.source in ("bot_observed", "player_confirmed", "player_marked"):
            if record.confidence >= 0.7:
                return PolicyResult(
                    WriteDecision.AUTO_WRITE,
                    reason=f"high-confidence {record.source} observation",
                )
            elif record.confidence >= 0.4:
                return PolicyResult(
                    WriteDecision.CANDIDATE,
                    reason="medium-confidence observation",
                )
            else:
                return PolicyResult(
                    WriteDecision.SHORT_TERM_ONLY,
                    reason="low-confidence observation",
                )

        # Imported records default to candidate (quarantine by Phase 8b)
        if record.source == "imported":
            return PolicyResult(
                WriteDecision.CANDIDATE,
                reason="imported — needs local verification",
                suggested_confidence=min(record.confidence, 0.5),
            )

        # Fallback
        return PolicyResult(
            WriteDecision.CANDIDATE,
            reason="unknown source — reviewing",
        )

    # ── Promote policy ──────────────────────────────────────────────────

    def evaluate_promote(
        self,
        record: MemoryRecord,
        *,
        access_count: int = 0,
        days_since_created: float = 0.0,
        has_expired: bool = False,
    ) -> PromoteDecision:
        """Decide whether a short-term memory should be promoted to long-term."""
        if has_expired:
            return PromoteDecision.DISCARD

        # Frequently accessed memories are worth keeping
        if access_count >= 3:
            return PromoteDecision.PROMOTE

        # High-confidence memories that are recent
        if record.confidence >= 0.8 and days_since_created < 7:
            return PromoteDecision.PROMOTE

        # Old, never-accessed memories → discard
        if days_since_created > 30 and access_count == 0:
            return PromoteDecision.DISCARD

        return PromoteDecision.KEEP_SHORT

    # ── Inject policy ───────────────────────────────────────────────────

    def plan_injection(
        self,
        records: list[MemoryRecord],
        token_budget: int = 2000,
    ) -> InjectPlan:
        """Decide which records to inject into the prompt and at what detail.

        Priority order: WORLD > BOT > MINECRAFT (more specific first).
        Within same scope: higher confidence first, then recency.
        """
        from .models import SCOPE_PRIORITY

        # Sort: scope priority ascending, then confidence descending, then recency
        sorted_records = sorted(
            records,
            key=lambda r: (
                SCOPE_PRIORITY.get(r.scope, 99),
                -r.confidence,
                -r.updated.timestamp(),
            ),
        )

        plan = InjectPlan()
        est_tokens = 0
        # Rough token estimate: ~1 token per 4 chars
        chars_per_token = 4

        for record in sorted_records:
            if est_tokens >= token_budget:
                break

            # High-confidence, scope=world → full inject
            if record.confidence >= 0.8 and record.scope == Scope.WORLD:
                body_tokens = len(record.body) // chars_per_token
                desc_tokens = len(record.description) // chars_per_token
                if est_tokens + body_tokens + desc_tokens <= token_budget:
                    plan.full.append(record)
                    est_tokens += body_tokens + desc_tokens
                    continue

            # Medium confidence or bot/minecraft scope → summary only
            desc_tokens = len(record.description) // chars_per_token
            if est_tokens + desc_tokens <= token_budget:
                plan.summary.append(record)
                est_tokens += desc_tokens
            else:
                # Last resort: name only in index
                plan.index.append(record.name)

        plan.total_tokens_est = est_tokens
        return plan

    # ── Scope validation ────────────────────────────────────────────────

    @staticmethod
    def validate_scope(record: MemoryRecord) -> PolicyResult:
        """Check that scope is appropriate for the record content.

        - scope=bot records must not contain coordinate literals or
          world-specific entity references.
        - scope=minecraft is read-only (Phase 7a static knowledge).
        """
        if record.scope == Scope.MINECRAFT:
            return PolicyResult(
                WriteDecision.REJECT,
                reason="scope=minecraft is read-only (Phase 7a static knowledge)",
            )

        if record.scope == Scope.BOT:
            # Quick scan for coordinate-like patterns in body
            import re

            coord_hints = re.findall(
                r"\(?-?\d{1,4},\s*-?\d{1,4},\s*-?\d{1,4}\)?", record.body
            )
            if coord_hints:
                return PolicyResult(
                    WriteDecision.REJECT,
                    reason=(
                        "scope=bot must not contain coordinates; "
                        "found potential coords in body.  "
                        "Use scope=world instead."
                    ),
                    suggested_scope=Scope.WORLD,
                )

        return PolicyResult(WriteDecision.AUTO_WRITE, reason="scope valid")
